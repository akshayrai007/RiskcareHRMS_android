                "To ensure location tracking works when app is closed:\n\n" +
                "1. Open Phone Settings\n2. Go to Battery → App Battery Management\n" +
                "3. Find $APP_NAME → Allow background activity ✅\n\n" +
                "Without this, tracking stops after closing the app."
        brand.contains("oneplus") ->
            "📍 Disable Deep Optimization" to
                "To ensure location tracking works when app is closed:\n\n" +
                "1. Open Phone Settings\n2. Go to Battery → Battery Optimization\n" +
                "3. Find $APP_NAME → Don't optimize ✅\n\n" +
                "Without this, tracking stops after closing the app."
        brand.contains("vivo") ->
            "📍 Enable Background Location" to
                "To ensure location tracking works when app is closed:\n\n" +
                "1. Open iManager app\n2. Go to App Manager → $APP_NAME\n" +
                "3. Enable Background Power Consumption ✅\n\n" +
                "Without this, tracking stops after closing the app."
        brand.contains("huawei") || brand.contains("honor") ->
            "📍 Enable AutoLaunch" to
                "To ensure location tracking works when app is closed:\n\n" +
                "1. Open Phone Settings\n2. Go to Apps → $APP_NAME → Battery\n" +
                "3. Enable Auto Launch & Run in background ✅\n\n" +
                "Without this, tracking stops after closing the app."
        brand.contains("samsung") ->
            "📍 Remove Battery Restriction" to
                "To ensure location tracking works when app is closed:\n\n" +
                "1. Open Phone Settings\n2. Go to Apps → $APP_NAME → Battery\n" +
                "3. Select Unrestricted ✅\n\n" +
                "Without this, Samsung stops tracking after ~10 minutes."
        else ->
            "📍 Allow Background Location" to
                "To ensure location tracking works when app is closed:\n\n" +
                "1. Open Phone Settings\n2. Go to Apps → $APP_NAME → Battery\n" +
